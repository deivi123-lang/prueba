/* =========================================================
   9. AUMENTAR CANTIDAD
========================================================= */

function aumentarCantidad(id) {

    const producto =
        carrito.find(
            producto => producto.id === id
        );


    if (producto) {

        producto.cantidad++;

        actualizarCarrito();

    }

}


/* =========================================================
   10. DISMINUIR CANTIDAD
========================================================= */

function disminuirCantidad(id) {

    const producto =
        carrito.find(
            producto => producto.id === id
        );


    if (!producto) {

        return;

    }


    if (producto.cantidad > 1) {

        producto.cantidad--;

    } else {

        carrito =
            carrito.filter(
                producto => producto.id !== id
            );

    }


    actualizarCarrito();

}


/* =========================================================
   11. ELIMINAR PRODUCTO
========================================================= */

function eliminarDelCarrito(id) {

    carrito =
        carrito.filter(
            producto => producto.id !== id
        );


    actualizarCarrito();

}


/* =========================================================
   12. CONTADOR
========================================================= */

function actualizarContador() {

    const cantidad =
        carrito.reduce(
            (total, producto) =>
                total + producto.cantidad,
            0
        );


    contadorCarrito.textContent =
        cantidad;

}


/* =========================================================
   13. TOTAL
========================================================= */

function actualizarTotal() {

    const total =
        carrito.reduce(
            (suma, producto) =>
                suma +
                producto.precio *
                producto.cantidad,
            0
        );


    totalCarrito.textContent =
        `Bs. ${total.toFixed(2)}`;

}


